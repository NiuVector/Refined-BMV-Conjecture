rng = np.random.default_rng(42)

# ============================================================
# 1. Refined BMV Lower Bound Probe:
#    A_{n,m}(e^a, e^b) >= Tr(e^{n*a + m*b})
#    and stronger: A_{n,m}(A, B) >= Tr((A^{n/m} B)^m)
# ============================================================
def bmv_avg_trace(A, B, n, m):
    # Compute sum of all words with n A's and m B's via DP
    # dp[i][j] = sum of all words with i A's and j B's
    d = A.shape[0]
    dp = [[None]*(m+1) for _ in range(n+1)]
    dp[0][0] = np.eye(d, dtype=np.complex128)
    for i in range(n+1):
        for j in range(m+1):
            if i == 0 and j == 0:
                continue
            mat = np.zeros((d, d), dtype=np.complex128)
            if i > 0:
                mat += dp[i-1][j] @ A
            if j > 0:
                mat += dp[i][j-1] @ B
            dp[i][j] = mat
    return np.real(np.trace(dp[n][m])) / math.comb(n+m, m)

def make_herm(x, d):
    H = np.zeros((d, d), dtype=np.complex128)
    idx = 0
    for i in range(d):
        H[i, i] = x[idx]; idx += 1
        for j in range(i+1, d):
            H[i, j] = x[idx] + 1j * x[idx+1]
            H[j, i] = x[idx] - 1j * x[idx+1]
            idx += 2
    return H

print("=== 1. Refined BMV Lower Bound Probe ===")
for (d, n, m) in [(4, 3, 3), (3, 4, 4), (3, 5, 3), (4, 4, 3)]:
    min_ratio_gt = 1e9
    min_ratio_strong = 1e9
    for trial in range(40):
        scale = rng.uniform(0.5, 4.0)
        # Diagonal alpha, general Hermitian beta
        a_eig = rng.normal(0, scale, d)
        a_eig -= np.mean(a_eig)
        alpha = np.diag(a_eig)
        H = make_herm(rng.normal(0, 1.0, d*d), d)
        U = expm(1j * H)
        b_eig = rng.normal(0, scale, d)
        b_eig -= np.mean(b_eig)
        beta = U @ np.diag(b_eig) @ U.conj().T
        A = np.diag(np.exp(a_eig))
        B = U @ np.diag(np.exp(b_eig)) @ U.conj().T
        lhs = bmv_avg_trace(A, B, n, m)
        rhs_gt = np.real(np.trace(expm(n * alpha + m * beta)))
        # Stronger: Tr((A^{n/m} B)^m)
        A_pow = np.diag(np.exp((n/m) * a_eig))
        rhs_strong = np.real(np.trace(np.linalg.matrix_power(A_pow @ B, m)))
        if rhs_gt > 0:
            min_ratio_gt = min(min_ratio_gt, lhs / rhs_gt)
        if rhs_strong > 0:
            min_ratio_strong = min(min_ratio_strong, lhs / rhs_strong)
    print(f"d={d}, (n,m)=({n},{m}): min LHS/Tr(exp(na+mb)) = {min_ratio_gt:.6f}, min LHS/Tr((A^(n/m)B)^m) = {min_ratio_strong:.6f}")

# ============================================================
# 2. Chollet's Permanent Conjecture Probe (n = 7)
#    per(A o A_bar) <= per(A)^2
# ============================================================
def ryser_perm(M):
    n = M.shape[0]
    row_sums = np.zeros(n, dtype=np.complex128)
    total = 0.0 + 0.0j
    # Gray code Ryser
    sign = 1
    prev_gray = 0
    for k in range(1, 1 << n):
        gray = k ^ (k >> 1)
        diff = gray ^ prev_gray
        col = diff.bit_length() - 1
        if gray & diff:
            row_sums += M[:, col]
        else:
            row_sums -= M[:, col]
        prev_gray = gray
        pop = bin(gray).count('1')
        prod = np.prod(row_sums)
        if (n - pop) % 2 == 0:
            total += prod
        else:
            total -= prod
    return total

print("\n=== 2. Chollet Permanent Probe (n=7, low-rank complex correlation) ===")
n = 7
best_chollet = 0.0
for r in [2, 3, 4]:
    for trial in range(60):
        V = rng.normal(size=(r, n)) + 1j * rng.normal(size=(r, n))
        V /= np.linalg.norm(V, axis=0, keepdims=True)
        A = V.conj().T @ V
        pA = np.real(ryser_perm(A))
        pAA = np.real(ryser_perm(np.abs(A)**2))
        if pA > 1e-12:
            ratio = pAA / (pA * pA)
            if ratio > best_chollet:
                best_chollet = ratio
print(f"n=7 random low-rank max per(|A|^2)/per(A)^2 = {best_chollet:.6f}")

