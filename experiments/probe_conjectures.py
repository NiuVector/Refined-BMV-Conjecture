# Character chi_1(g^k) = omega^k
max_ratio_C5 = 0.0
for trial in range(200):
    V = rng.normal(size=(3, 5)) + 1j * rng.normal(size=(3, 5))
    V /= np.linalg.norm(V, axis=0, keepdims=True)
    A = V.conj().T @ V
    pA = np.real(ryser_perm(A))
    dchi = 0j
    for k, p in enumerate(perms_C5):
        prod = 1.0 + 0j
        for i in range(5):
            prod *= A[i, p[i]]
        dchi += (omega**k) * prod
    val = np.real(dchi)
    if pA > 1e-12:
        max_ratio_C5 = max(max_ratio_C5, val / pA)
print(f"n=5 C5 random max d_chi/per(A) = {max_ratio_C5:.6f}")
